// Command gen trains the character-bigram table used by package wordy from
// the words found in a corpus of text/source files and writes table.go.
//
//	go run ./internal/wordy/gen -out internal/wordy/table.go DIR...
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"math"
	"os"
	"path/filepath"
	"strings"

	"github.com/AISolutionLabs/secret-scanner/internal/wordy"
)

func main() {
	out := flag.String("out", "table.go", "output Go file")
	exts := flag.String("ext", ".py,.go,.md,.txt,.rst", "file extensions to read")
	maxFiles := flag.Int("max-files", 5000, "cap on files read")
	flag.Parse()
	allowed := map[string]bool{}
	for _, e := range strings.Split(*exts, ",") {
		allowed[e] = true
	}
	var counts [28][28]float64
	files := 0
	for _, root := range flag.Args() {
		filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
			if err != nil || d.IsDir() || files >= *maxFiles || !allowed[filepath.Ext(p)] {
				return nil
			}
			data, err := os.ReadFile(p)
			if err != nil {
				return nil
			}
			files++
			for _, w := range wordy.Tokens(string(data)) {
				w = "^" + strings.ToLower(w) + "$"
				for i := 0; i+1 < len(w); i++ {
					counts[idx(w[i])][idx(w[i+1])]++
				}
			}
			return nil
		})
	}
	if files == 0 {
		fmt.Fprintln(os.Stderr, "gen: no training files found")
		os.Exit(1)
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/wordy/gen from %d files; DO NOT EDIT.\n// SPDX-License-Identifier: Apache-2.0\n\npackage wordy\n\n", files)
	b.WriteString("// table[a][b] = log P(b | a) over ^, a-z, $ (Laplace-smoothed).\nvar table = [28][28]float32{\n")
	for a := 0; a < 28; a++ {
		var tot float64
		for c := 0; c < 28; c++ {
			tot += counts[a][c] + 1
		}
		b.WriteString("\t{")
		for c := 0; c < 28; c++ {
			fmt.Fprintf(&b, "%.3f, ", math.Log((counts[a][c]+1)/tot))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Printf("trained on %d files -> %s\n", files, *out)
}

func idx(c byte) int {
	switch {
	case c == '^':
		return 0
	case c == '$':
		return 27
	}
	return int(c-'a') + 1
}
